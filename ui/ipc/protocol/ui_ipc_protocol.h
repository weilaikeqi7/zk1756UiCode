#else
_Static_assert(sizeof(UiIpcTimestamp) == 16, "IPC timestamp layout changed");
_Static_assert(sizeof(UiIpcMessageHeader) == 18, "IPC message header layout changed");
#endif

static inline ROE_U8 ui_ipc_concrete_type(ROE_SL msgType)
{
    /* Every protocol group stores its local type in the low byte. */
    return (ROE_U8)((ROE_U64)msgType & 0xFFU);
}

