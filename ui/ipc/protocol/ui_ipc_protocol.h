typedef struct {
    int64_t seconds;
    int64_t microseconds;
} UiIpcTimestamp;

typedef struct {
    ROE_U8 version; // 版本
    ROE_U8 concreteMsgType; // 具体类型
    UiIpcTimestamp timestamp; // 时间戳，秒/微秒
} UiIpcMessageHeader;

